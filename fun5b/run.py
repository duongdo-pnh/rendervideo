def _hold_known_latents():
    """Make the pipeline keep every latent frame whose frames are all known (a chunk's KNOWN=13 finished frames: 4
    latents) as given, at timestep 0, on every step. VideoX-Fun keeps only latent 0 that way (it sets the mask of all
    later latents to "generate"), so latents 1-3 were drawn again from noise, guided by the inpainting channels only,
    and every chunk went on from that softer redraw. TMF 30s clip, same seed: fine detail (high-pass energy) +3% on
    the shirt and +4% on the hair over the whole video, the first new frame of a chunk 0.96 -> 0.99 of its
    neighbourhood; the frames after it still dip (~0.95: the known frames have been through a VAE decode and encode).
    Same render time (1195s against 1191s). The latent mask the pipeline builds is the first frame of each 4-frame
    group, so the known frames must end a group: KNOWN = 4k + 1."""
    if (KNOWN - 1) % 4:
        raise ValueError("KNOWN must be 4k + 1 to hold the known latents")
    from videox_fun.pipeline import pipeline_wan2_2_fun_control as module

    cls = module.Wan2_2FunControlPipeline
    if getattr(cls, "_holds_known", False):
        return
    lines, first = inspect.getsourcelines(cls.__call__)
    source = "".join(lines)
    old = "mask[:, :, 1:, :, :] = 1\n"
    if source.count(old) != 1:
        raise RuntimeError("VideoX-Fun's Wan2_2FunControlPipeline changed: cannot hold the known latents")
    new = "mask[:, :, next((k for k in range(1, mask.shape[2]) if mask[:, :, k].any()), mask.shape[2]):, :, :] = 1\n"
    lines = source.replace(old, new).split("\n")
    depth = len(lines[0]) - len(lines[0].lstrip())
    namespace = {}
    code = "\n" * (first - 1) + "\n".join(line[depth:] for line in lines)  # the file's line numbers in tracebacks
    exec(compile(code, module.__file__, "exec"), module.__dict__, namespace)
    cls.__call__, cls._holds_known = namespace["__call__"], True


def apply_preset(pipe, preset):
    """Set the LoRA weight (merging only the difference, a few seconds) and the prompt embeddings of a preset;
    returns (steps, guidance scale)."""
    lora, steps, guidance, neg_light = PRESETS[preset]
    if lora != pipe.lora_weight:
        _merge_lora(pipe.transformer, LORA, lora - pipe.lora_weight)
        pipe.lora_weight = lora
    pipe.cached_prompt_embeds = pipe.embeds[neg_light]
    return steps, guidance


def read_driving(video_path, fps=config.FPS):
    """Driving frames (RGB) resampled to `fps` and center-cropped/resized to the render size, yielded 64 decoded at a
    time so a long video is never held in memory whole. Decoded in a background thread while the caller runs pose
    detection on the previous batch, and resized with OpenCV (area): PIL's Lanczos took 70 of 139 ms per frame, and
    these frames only feed the pose detector. decord picks the frames (count, rate, timestamps); PyAV decodes them
    with FFmpeg's frame threads (see _read_av) and decord decodes whatever PyAV does not."""
    vr = VideoReader(video_path, ctx=cpu(0))
    src_fps = vr.get_avg_fps()
    idx = np.minimum(np.round(np.arange(int(len(vr) / src_fps * fps)) * src_fps / fps).astype(int), len(vr) - 1)
    batches = queue.Queue(maxsize=2)

    def decode():
        try:
            start = _read_av(video_path, idx, vr.get_frame_timestamp(idx)[:, 0], 0.25 / src_fps, batches.put)
            for s in range(start, len(idx), 64):
                batches.put([_fit(f) for f in vr.get_batch(idx[s : s + 64]).asnumpy()])
        except BaseException as e:  # noqa: BLE001 - raised in the caller instead of leaving it waiting forever
            batches.put(e)
        else:
            batches.put(None)

    threading.Thread(target=decode, daemon=True).start()
    while (batch := batches.get()) is not None:
        if isinstance(batch, BaseException):
            raise batch
        yield from batch


def _read_av(video_path, idx, stamps, tolerance, put):
    """put() the _fit() frames `idx` (sorted frame numbers, repeats allowed) decoded with PyAV, 64 at a time, as long as
    they are the frames decord would give: 8-bit 4:2:0 only (the RGB conversion was checked bit for bit against
    decord's on that) and each frame's timestamp within `tolerance` of decord's `stamps`. Returns how many of `idx`
    were put; decord decodes the rest. decord decodes on one thread here: 34s of the ~65s "pose" step for 30s of
    1080×1920 60fps, against 13s with FFmpeg's frame threads, the same frames bit for bit."""
    try:
        import av
    except ImportError:
        return 0
    pos, batch = 0, []
    try:
        container = av.open(video_path)
    except av.FFmpegError:
        return 0
    with container:
        stream = container.streams.video[0]
        if stream.codec_context.pix_fmt != "yuv420p":
            return 0
        stream.thread_type = "FRAME"
        try:
            for i, frame in enumerate(container.decode(stream)):
                if pos == len(idx):
                    break
                if idx[pos] != i:
                    continue
                if frame.format.name != "yuv420p" or frame.time is None or abs(frame.time - stamps[pos]) > tolerance:
                    break
                fitted = _fit(frame.to_ndarray(format="rgb24"))
                while pos < len(idx) and idx[pos] == i:
                    batch.append(fitted)
                    pos += 1
                if len(batch) >= 64:
                    put(batch)
                    batch = []
        except av.FFmpegError:  # a damaged frame: decord decodes from there
            pass
    if batch:
        put(batch)
    return pos


def driving_poses(detector):
    """The DrivingPoses (pose detections cached per driving video) of render(): the frames as read_driving() gives
    them. Create one per detector and pass it to every render; the UI also starts it on upload (prefetch)."""
    reader = "".join(inspect.getsource(f) for f in (_read_av, _fit))  # read_driving's own source is in the key already
    spec = f"read_driving {config.FPS}fps {RENDER_W}x{RENDER_H} cv2-area {hashlib.sha256(reader.encode()).hexdigest()}"
    return DrivingPoses(detector, read_driving, spec=spec)


def _motion_speed(before, after):
    """How far the hands and arms move from pose `before` to pose `after` (px): the largest of each hand's mean
    keypoint shift and each elbow's and wrist's shift, over the points seen in both."""
    moves = []
    for points in (np.r_[92:113], np.r_[113:134], [3], [4], [6], [7]):
        seen = (before[points, 2] > 0.3) & (after[points, 2] > 0.3)
        if seen.any():
            moves.append(np.linalg.norm(after[points, :2] - before[points, :2], axis=1)[seen].mean())
    return max(moves, default=0.0)


def slow_motion_poses(poses, lead, threshold=SLOW_MOTION, most=SLOW_MOTION_MAX):
    """
    The frames to generate for `poses`, as (times, poses): times in frames of `poses` (floats), whole numbers where a
    pose of `poses` is drawn; render() writes only those. Each step from frame i - 1 to i whose hands or arms move
    more than `threshold` px is split into k = ceil(speed / threshold) steps (at most `most`), the keypoints moved in
    a straight line (scores: the lower of the two), so the model draws the fast moves in slow motion and the frames in
    between are dropped. The lead-in (the first `lead` poses, dropped anyway) is not split. threshold None: every
    pose once, as before.
    Why: Wan learned from 24-30fps video, where a hand moving 15-30 px per frame is motion-blurred and see-through,
    and it draws fast hands that way, in the raw frames, before any matting: in a 30s pharmacy render the hands came
    out ghosted (smeared, half transparent, the shirt showing through the fingers, double copies) in 2% of the
    hand-frames below 3 px/frame, 17% at 14-18 and 47% above 22. Steps (28), CFG 3 with a motion-blur negative
    prompt, the sampler, shift and the seed did not change it; slower motion did. Two 112-frame clips of that video
    with its fastest clapping (33 frames at 14-27 px/frame, 66 hand-frames), counted by eye side by side and blind:
    ghosted hand-frames 44 (seed 2: 42) -> 18 (seed 2: 15) at 15 px, 27 at 18 px, ~20 at 12 px, 17 at 10 px and 17
    with every frame generated twice. The whole 30s video at 15 px, the 63 frames above 16 px/frame (126
    hand-frames), counted blind: 56 -> 20 ghosted; face colour within 0.2 L, background and table the same (top and
    bottom 150 rows of the video: mean difference < 0.01 levels). Cost: the generated frames, 995 instead of 897
    there (+11%; +23% at 12 px, +37% at 10): 1335s instead of 1185-1190s (RTX 3090). A short clip can pay more
    (3.7s: +19-26%, one more small chunk); the 12 cached driving videos: 0-15% more frames.
    """
    times, out = [], []
    for i, pose in enumerate(poses):
        k = 1
        if threshold and i > lead:
            k = int(np.clip(np.ceil(_motion_speed(poses[i - 1], pose) / threshold), 1, most))
        for q in range(1, k):
            w = q / k
            mid = pose.copy()
            mid[:, :2] = (1 - w) * poses[i - 1][:, :2] + w * pose[:, :2]
            mid[:, 2] = np.minimum(poses[i - 1][:, 2], pose[:, 2])
            times.append(i - 1 + w)
            out.append(mid)
        times.append(float(i))
        out.append(pose)
    return times, out


OUT_SHARPEN = 0.4  # unsharp amount, see _to_output
ENCODE_PARAMS = ["-bf", "0", "-x264-params", "keyint=900:min-keyint=900:scenecut=0"]  # see render()


def _to_output(frame):
    """A finished 640×1152 frame as the 720×1280 one written. The 1.125× enlargement alone took a quarter of the fine
    detail (sleeve cuffs, buttons, lining: Laplacian 6.6 -> 5.1 on a 6s clip); a mild unsharp mask (σ 1.2) brings it
    back to the sharpness the frame had (6.6). The codec's quality barely mattered (q8 5.07, q10 5.16 at 5x the size)."""
    big = cv2.resize(frame, (OUT_W, OUT_H), interpolation=cv2.INTER_LANCZOS4).astype(np.float32)
    soft = cv2.GaussianBlur(big, (0, 0), 1.2)
    return np.clip(big + OUT_SHARPEN * (big - soft), 0, 255).astype(np.uint8)


def _fit(frame):
    """Center-crop `frame` to the render aspect and resize it to the render size (as PIL's ImageOps.fit)."""
    height, width = frame.shape[:2]
    if width * RENDER_H > height * RENDER_W:  # too wide
        crop = round(height * RENDER_W / RENDER_H)
        frame = frame[:, (width - crop) // 2 : (width - crop) // 2 + crop]
    else:
        crop = round(width * RENDER_H / RENDER_W)
        frame = frame[(height - crop) // 2 : (height - crop) // 2 + crop]
    return cv2.resize(frame, (RENDER_W, RENDER_H), interpolation=cv2.INTER_AREA)


@torch.no_grad()
def render(pipe, detector, image, video_path, out_path, preset=DEFAULT_PRESET, seed=config.DEFAULT_SEED, log=print,
           cancel=None, matting=None, table_line=None, poses_cache=None, background=None, slow_motion=None):
    """Animate `image` with the motion of `video_path` into `out_path` (exactly 720×1280 at 30fps); returns the number
    of frames written. Frames are written as they are finished, so memory does not grow with the video's length; a
    cancelled or failed render leaves no file.
    `cancel`: optional callable checked after every denoising step (raises Cancelled). `matting`: a Matting to keep
    the reference's background and lighting (every frame is composited onto a plate made from the reference).
    `table_line`: with matting, keep everything below this fraction of the height exactly as in the reference.
    `background`: with matting, an image of the same scene without the person, used as the plate.
    `poses_cache`: a driving_poses(detector), so the driving video's pose detection is done once (default: a new one,
    which still finds the detections cached on disk by an earlier render of the same video).
    `slow_motion`: e.g. SLOW_MOTION, draw hand and arm moves faster than this many px per frame in slow motion (solid
    instead of ghosted hands; +12% render time on a 30s clip with fast clapping), see slow_motion_poses(); None: off."""
    from videox_fun.utils import get_image_latent, get_image_to_video_latent, get_video_to_video_latent

    steps, guidance = apply_preset(pipe, preset)
    reference = ImageOps.fit(image.convert("RGB"), (RENDER_W, RENDER_H), Image.LANCZOS)
    tic = time.time()
    detections = (poses_cache if poses_cache is not None else driving_poses(detector))(video_path)  # cached per video
    lead = 1 + LEAD_IN + SETTLE
    times, poses = slow_motion_poses(pose_frames(detector, np.asarray(reference), detections, lead_in=LEAD_IN,
                                                 settle=SETTLE), lead,
                                     slow_motion)
    written = [t >= lead and t == int(t) for t in times]  # in-between (slow motion) frames are generated, not written
    total = len(poses)
    log(f"pose: {sum(written)} frames ({total} generated) in {time.time() - tic:.0f}s")

    sample_size = [RENDER_H, RENDER_W]
    # VideoX-Fun's helpers read from files: kept next to out_path (the job's own work dir), so two renders never share them.
    work_dir = os.path.dirname(os.path.abspath(out_path))
    os.makedirs(work_dir, exist_ok=True)
    ref_path = os.path.join(work_dir, ".fun5b_ref.png")
    reference.save(ref_path)
    ref_latent = get_image_latent(ref_path, sample_size=sample_size)
    clean = np.asarray(ImageOps.fit(background.convert("RGB"), (RENDER_W, RENDER_H), Image.LANCZOS)) \
        if background is not None else None  # the scene without the person: used instead of painting her out
    plate = matting.plate(np.asarray(reference), table_line, clean) if matting is not None else None
    table_known = getattr(matting, "table_known", None) if matting is not None else None

    def on_step_end(pipeline, i, t, callback_kwargs):
        if cancel is not None and cancel():
            raise Cancelled
        return callback_kwargs

    raw = []  # generated frames (blended across chunk seams); finalized ones are released
    final = []  # finished frames, composited onto the plate when matting; only the tail the next chunk needs is kept
    if matting is not None:
        matting.reset()
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    # No B-frames and one keyframe: B-frames kept ~5% less fine detail (eyes, fabric) every other frame, a pulse at
    # 15Hz, and the keyframe at 250 made the static background tick; the file is ~50% bigger.
    writer = imageio.get_writer(out_path, fps=config.FPS, quality=8, macro_block_size=8,
                                output_params=config.VIDEO_COLOR_PARAMS + ENCODE_PARAMS)

    last_drawn = []  # the model's own last SEAM frames, before compositing: what the next chunk's light is matched to

    face_lock = FaceLock(np.asarray(reference), detector, matting.ref_alpha) if matting is not None else None
    if matting is not None:  # poses[0]: the reference's own pose (the lead-in starts from it). Not without the face
        # lock: composite() would measure its own lock on the held matte, which the colour targets were not made on.
        matting.hold(poses[0] if face_lock.target is not None else None)

    def finalize(upto):
        start = len(final)
        if matting is not None:
            # The chunk is matted first (in order: RVM is recurrent), so the colour lock measures the clothes on it.
            mattes = [(fgr, alpha.astype(np.float16)) for fgr, alpha in map(matting, raw[start:upto])]
            locks = face_lock.corrections(raw[start:upto], poses[start:upto], [alpha for _, alpha in mattes])
            # The head and sleeves held solid (Matting.hold) only for compositing: the colour groups were learned on
            # RVM's alpha, and a held bun counted among the clothes moved their lock.
            mattes = [(fgr, alpha.astype(np.float16)) for fgr, alpha in
                      (matting.held(raw[i], mattes[i - start], plate, poses[i]) for i in range(start, upto))]
        for i in range(start, upto):
            if matting is None:
                final.append(raw[i])
            elif locks is not None and locks.ndim == 3:  # a correction per region: head, colour groups
                final.append(matting.composite(raw[i], plate, locks[i - start], mattes[i - start],
                                               head_map(raw[i].shape[:2], poses[i]), face_lock.centres))
            else:
                final.append(matting.composite(raw[i], plate, None if locks is None else locks[i - start],
                                               mattes[i - start]))
            last_drawn[:] = (last_drawn + [raw[i]])[-SEAM:]
            raw[i] = None
            if written[i]:  # the lead-in frames (reference pose moving to the first driving pose) are dropped
                writer.append_data(_to_output(final[i]))
        for i in range(max(0, len(final) - KNOWN - BLEND)):  # the next chunk starts from the last KNOWN + BLEND
            final[i] = None

    try:
        generator = torch.Generator("cuda").manual_seed(seed)
        tic = time.time()
        while len(final) < total:
            # Chunk 0 starts from the reference image as a known frame. Chunk k > 0 starts KNOWN + BLEND frames before
            # the end: the first KNOWN are given as known frames (finished ones, on the plate), the next BLEND are
            # generated again and cross-faded with the previous chunk's.
            start = max(len(raw) - KNOWN - BLEND, 0) if raw else 0
            known = final[start : start + KNOWN] if raw else [np.asarray(reference)]
            length = min(CHUNK, total - start)
            n = length + (-(length - 1)) % 4  # the VAE needs 4k+1 frames: pad with the last pose, drop afterwards
            control = [draw_pose_frame(poses[min(i, start + length - 1)], RENDER_H, RENDER_W)
                       for i in range(start, start + n)]
            control_path = os.path.join(work_dir, ".fun5b_control.mp4")
            imageio.mimwrite(control_path, control, fps=config.FPS, quality=8, macro_block_size=8)
            ctrl, _, _, _ = get_video_to_video_latent(control_path, video_length=n, sample_size=sample_size,
                                                      fps=config.FPS)
            start_frames = [Image.fromarray(f) for f in known] or None
            video, mask, _ = get_image_to_video_latent(start_frames, None, video_length=n, sample_size=sample_size)
            if table_known is not None:
                _give_table(video, mask, np.asarray(reference), table_known,
                            [poses[min(i, start + length - 1)] for i in range(start, start + n)])
            latents = pipe(
                PROMPT, negative_prompt=NEGATIVE, num_frames=n, height=RENDER_H, width=RENDER_W, generator=generator,
                guidance_scale=guidance, num_inference_steps=steps, video=video, mask_video=mask, control_video=ctrl,
                control_camera_video=None, ref_image=ref_latent, boundary=pipe.boundary, shift=SHIFT,
                callback_on_step_end=on_step_end, output_type="latent",
            ).videos
            frames = pipe.decode_video(latents, length)  # uint8 (length, H, W, 3)
            del latents
            if raw:
                if matting is None:  # with matting, fun5b.facelock holds the face and the clothes across the seam
                    frames = _match_chunk(frames, len(known), last_drawn, detector)
                overlap = len(raw) - start - KNOWN  # == BLEND except when the video is shorter than that
                for j in range(overlap):  # linear cross-fade from the previous chunk into this one
                    w = (j + 1) / (overlap + 1)
                    i = start + KNOWN + j
                    raw[i] = ((1 - w) * raw[i] + w * frames[KNOWN + j]).round().astype(np.uint8)
                raw.extend(frames[KNOWN + overlap :])
            else:
                raw.extend(frames)
            done = len(raw) >= total
            finalize(total if done else len(raw) - BLEND)  # the last BLEND frames get cross-faded with the next chunk
            log(f"chunk: {sum(written[:len(raw)])}/{sum(written)} frames ({time.time() - tic:.0f}s)")

    except BaseException:
        writer.close()
        if os.path.exists(out_path):  # the writer creates the file with its first frame
            os.remove(out_path)
        raise
    finally:
        for tmp in (ref_path, os.path.join(work_dir, ".fun5b_control.mp4")):
            if os.path.exists(tmp):
                os.remove(tmp)
    writer.close()
    return sum(written)


def _give_table(video, mask, reference, known_row, frame_poses):
    """
    Give the model the reference from `known_row` down (the table and, from the latent row above the table line, the
    last rows of her body; Matting.plate() picks the row, see fun5b.matting._table_known) as known pixels in every
    frame it generates (`video`/`mask` of get_image_to_video_latent, changed in place), so it draws the person down
    to the reference's table. Without this it drew its own table edge 5-15px higher, moving from frame to frame, and
    cut her there: on the plate she stopped short of the table and the plate showed in the gap. The inpainting
    channels of Wan2.2-Fun-Control take static spatial masks (VideoX-Fun trains them with get_random_mask), and the
    cost is nil (the masked video is encoded anyway). The known region starts on a whole latent row (16px): a latent
    row half known, half masked (masked pixels are grey) drew a grey smear 20-30px tall above the table. Frames whose
    hands reach the known rows (and the rest of their latent frame) get nothing, so the model can still draw hands
    over the table. The reference, not the clean plate: they agree below the table line, and above it the plate has
    the background where her body is.
    """
    if known_row <= 0 or known_row >= video.shape[-2]:  # all known would freeze the frames (known latents are held)
        return
    frames = video.shape[2]
    low = np.array([bool(((kp[92:134, 2] > 0.3) & (kp[92:134, 1] > known_row)).any()
                         or ((kp[[4, 7], 2] > 0.3) & (kp[[4, 7], 1] > known_row)).any()) for kp in frame_poses])
    for first in range(1, frames, 4):  # a latent frame packs 4 frames (the first one alone)
        low[first : first + 4] = low[first : first + 4].any()
    table = torch.from_numpy(np.ascontiguousarray(reference[known_row:])).permute(2, 0, 1).float() / 255
    for f in range(frames):
        if mask[0, 0, f].min() > 127 and not low[f]:  # a frame to generate
            video[0, :, f, known_row:] = table
            mask[0, 0, f, known_row:] = 0


def _match_chunk(frames, known, previous, detector):
    """
    Keep the model's light continuous across a chunk seam. A chunk is given the last KNOWN finished frames, which are
    composited and colour-locked (the lock brightened the face ~3% here), and redraws them as given; its new frames
    then carry that brightening into the raw frames, the colour lock applied it once more, and every seam stepped the
    face up (+6 then +10 L, accumulating). So the face in the first SEAM new frames (frames[known:]) is matched to
    the face in `previous`, the model's own last SEAM frames before compositing, one frame apart: L scaled, a/b
    shifted, for the whole chunk. The face, because that is where the step shows: over the whole person a white coat
    and a dark apron dominate and hid it.
    Only without matting. With it, the colour lock restarts at every seam and takes each region to the reference
    from the chunk's first frame, which this match then only got in the way of: the model relights face and clothes
    differently at a chunk start (pharmacy clip: face +5 L, scrubs -3..-5 L), the face-derived gain put that
    difference on the scrubs as a -7 L step (and the lock already held the face), and the match against the previous
    raw frames, not the finished ones the chunk was given, darkened every chunk (x0.93-0.99, b -3..-6), which the
    lock then had to climb back from (gain 1.06, b +5.7 by 30s).
    """
    added = frames[known : known + SEAM]
    target, drawn = _face_pixels(previous, detector), _face_pixels(added, detector)
    if len(target) < 200 or len(drawn) < 200:  # no face to go by
        return frames
    target, drawn = target.mean(0), drawn.mean(0)
    gain = float(np.clip(target[0] / max(drawn[0], 1.0), 0.85, 1.18))
    shift = np.clip(target[1:] - drawn[1:], -8, 8)
    print(f"chunk colour match (face): L x{gain:.3f}, a/b {shift[0]:+.1f} {shift[1]:+.1f}", flush=True)
    out = np.empty_like(frames)
    for i, f in enumerate(frames):
        lab = _lab(f).astype(np.float32)
        lab[..., 0] *= gain
        lab[..., 1:] += shift
        out[i] = cv2.cvtColor(np.clip(lab, 0, 255).round().astype(np.uint8), cv2.COLOR_LAB2RGB)
    return out


def _face_pixels(images, detector):
    """Lab pixels (N, 3) inside the face outline (DWPose's 68 face points, shrunk off the hairline and jaw edge)."""
    pixels = []
    for image in images:
        kp = detector(image)
        if kp is None:
            continue
        face = kp[24:92][kp[24:92, 2] > 0.3, :2]
        if len(face) < 40:
            continue
        mask = cv2.fillPoly(np.zeros(image.shape[:2], np.uint8), [cv2.convexHull(face.astype(np.int32))], 1)
        mask = cv2.erode(mask, np.ones((7, 7), np.uint8)).astype(bool)
        pixels.append(_lab(image)[mask])
    return np.concatenate(pixels) if pixels else np.zeros((0, 3), np.uint8)


def _lab(rgb):
    return cv2.cvtColor(rgb, cv2.COLOR_RGB2LAB)

