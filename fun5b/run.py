def _load_pipeline(GpuPipeline, AutoencoderKLWan3_8, AutoTokenizer, Wan2_2Transformer3DModel, WanT5EncoderModel,
                   FlowMatchEulerDiscreteScheduler, filter_kwargs):
    _use_sage_attention()
    _use_fast_rope()
    if HOLD_KNOWN:
        _hold_known_latents()
    cfg =OmegaConf.load(os.path.join(FUN_ROOT, "config/wan2.2/wan_civitai_5b.yaml"))
    dtype = torch.bfloat16
    # Loaded one at a time and moved to the GPU right away: all three in host RAM at once (~24GB + load copies) is
    # OOM-killed on a 32GB machine. T5 is dropped after encoding the fixed prompt (only the cached embeds are used).
    vae = AutoencoderKLWan3_8.from_pretrained(
        os.path.join(MODEL_DIR, cfg["vae_kwargs"].get("vae_subpath", "vae")),
        additional_kwargs=OmegaConf.to_container(cfg["vae_kwargs"]),
    ).to(dtype).to("cuda")
    lean_vae()  # bitwise the same output with less memory and time (fun5b/vae_decode.py)
    if os.environ.get("FUN5B_FAST_ENCODE", "1") != "0":
        # Bitwise the same latents; the masked start video of a chunk 9.0 -> 3.0s (see fun5b/vae_encode.py).
        from fun5b.vae_encode import install

        install(vae)
    gc.collect()
    text_encoder = WanT5EncoderModel.from_pretrained(
        os.path.join(MODEL_DIR, cfg["text_encoder_kwargs"].get("text_encoder_subpath", "text_encoder")),
        additional_kwargs=OmegaConf.to_container(cfg["text_encoder_kwargs"]), low_cpu_mem_usage=True, torch_dtype=dtype,
    ).eval().to("cuda")
    gc.collect()
    tokenizer = AutoTokenizer.from_pretrained(
        os.path.join(MODEL_DIR, cfg["text_encoder_kwargs"].get("tokenizer_subpath", "tokenizer")))
    scheduler = FlowMatchEulerDiscreteScheduler(
        **filter_kwargs(FlowMatchEulerDiscreteScheduler, OmegaConf.to_container(cfg["scheduler_kwargs"]))
    )
    pipe = GpuPipeline(transformer=None, transformer_2=None, vae=vae, tokenizer=tokenizer,
                       text_encoder=text_encoder, scheduler=scheduler)
    with torch.no_grad():
        pipe.embeds = {
            neg_light: pipe.encode_prompt(PROMPT, (NEGATIVE_LIGHT if neg_light else "") + NEGATIVE,
                                          do_classifier_free_guidance=True, device=torch.device("cuda"), dtype=dtype)
            for neg_light in (False, True)
        }
    pipe.register_modules(text_encoder=_NoTextEncoder())  # __call__ still reads text_encoder.dtype
    del text_encoder
    gc.collect()
    torch.cuda.empty_cache()
    transformer = Wan2_2Transformer3DModel.from_pretrained(
        os.path.join(MODEL_DIR, cfg["transformer_additional_kwargs"].get("transformer_low_noise_model_subpath",
                                                                       "transformer")),
        transformer_additional_kwargs=OmegaConf.to_container(cfg["transformer_additional_kwargs"]), torch_dtype=dtype,
        low_cpu_mem_usage=True,  # the default path builds the model in fp32 first: ~20GB of host RAM for 5B params
    ).to(dtype).to("cuda")
    gc.collect()
    if os.environ.get("FUN5B_COMPILE", "1") != "0":
        # torch.compile in place (module names stay, so the LoRA merge still finds them): 6.1 -> 5.3 s per step at a
        # 121-frame chunk, output within 43 dB PSNR of eager; ~30s to compile on the first step of each chunk size.
        transformer.compile(dynamic=False)
    pipe.register_modules(transformer=transformer)
    pipe.boundary = cfg["transformer_additional_kwargs"].get("boundary", 0.875)
    pipe.lora_weight = 0.0
    pipe.decode_need, pipe.decode_offload = {}, set()  # see GpuPipeline.decode_video
    return pipe


def _free_gpu():
    """Bytes this process can still allocate on the GPU: free device memory plus its own cached, unused blocks."""
    free, _ = torch.cuda.mem_get_info()
    return free + torch.cuda.memory_reserved() - torch.cuda.memory_allocated()


def _use_sage_attention():
    """SageAttention 1 (Triton, INT8 QK; pip install sageattention==1.0.6) for VideoX-Fun's attention, if installed:
    1.84x faster than PyTorch SDPA at a chunk's 22.5k tokens on an RTX 3090 (cosine 0.9999 to SDPA). VideoX-Fun has the
    hook; this wraps it to the fp16 the kernel takes. The SDPA path it replaces ignores the text padding mask too."""
    try:
        from sageattention import sageattn
    except ImportError:
        return
    import videox_fun.models.attention_utils as attention_utils

    def sage(q, k, v, attn_mask=None, tensor_layout="NHD", is_causal=False, dropout_p=0.0):
        if attn_mask is not None or dropout_p:
            raise ValueError("SageAttention: no attention mask or dropout")
        return sageattn(q.half(), k.half(), v.half(), tensor_layout=tensor_layout, is_causal=is_causal).to(q.dtype)

    attention_utils.sageattn, attention_utils.SAGE_ATTENTION_AVAILABLE = sage, True
    os.environ.setdefault("VIDEOX_ATTENTION_TYPE", "SAGE_ATTENTION")


@torch.compile(dynamic=False)
def _rope_rotate_qk(q, k, freqs):
    """Wan's RoPE rotation of q and k ([L, heads, 128]) by `freqs` ([L, 1, 64, 2] float64 cos/sin) in one fused kernel,
    with exactly the arithmetic of VideoX-Fun's rope_apply: x as complex64 promoted to complex128,
    (a + bi)(c + di) = (a*c - b*d) + (a*d + b*c)i, float64 -> x's dtype."""

    def rotate(x):
        length, heads, dims = x.shape
        pairs = x.float().reshape(length, heads, dims // 2, 2).double()
        a, b = pairs[..., 0], pairs[..., 1]
        c, d = freqs[..., 0], freqs[..., 1]
        return torch.stack([a * c - b * d, a * d + b * c], dim=-1).flatten(2).to(x.dtype)

    return rotate(q), rotate(k)


_rope_freqs = {}


@torch.amp.autocast("cuda", enabled=False)
@torch.compiler.disable()
def _rope_apply_qk(q, k, grid_sizes, freqs):
    """Drop-in for VideoX-Fun's rope_apply_qk, bitwise identical (checked on real q/k of a 121-frame chunk, with
    padding and with two samples), 10.4 -> 3.8 ms per block at a 121-frame chunk, ~0.2s per step: the eager version
    spends most of its time on float64 temporaries, the cat/stack copies of them and rebuilding the freqs."""
    c = q.size(3) // 2
    out_q, out_k = [], []
    for i, (f, h, w) in enumerate(grid_sizes.tolist()):
        seq_len = f * h * w
        key = (freqs.data_ptr(), f, h, w)
        if key not in _rope_freqs:
            parts = freqs.split([c - 2 * (c // 3), c // 3, c // 3], dim=1)
            if len(_rope_freqs) > 8:
                _rope_freqs.clear()
            _rope_freqs[key] = torch.view_as_real(torch.cat([
                parts[0][:f].view(f, 1, 1, -1).expand(f, h, w, -1),
                parts[1][:h].view(1, h, 1, -1).expand(f, h, w, -1),
                parts[2][:w].view(1, 1, w, -1).expand(f, h, w, -1),
            ], dim=-1).reshape(seq_len, 1, -1)).contiguous()
        rq, rk = _rope_rotate_qk(q[i, :seq_len], k[i, :seq_len], _rope_freqs[key])
        if q.size(0) == 1 and seq_len == q.size(1):  # no padding: skip the copies
            return rq.unsqueeze(0), rk.unsqueeze(0)
        out_q.append(torch.cat([rq, q[i, seq_len:]]))
        out_k.append(torch.cat([rk, k[i, seq_len:]]))
    return torch.stack(out_q), torch.stack(out_k)


