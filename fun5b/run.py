def _merge_lora(model, path, weight=1.0):
    """Merge a Kijai-format LoRA (diffusion_model.<module>.lora_down/lora_up, .diff_b, .diff) into the weights.
    VideoX-Fun's merge_lora cannot parse the .diff_b/.diff keys."""
    from safetensors.torch import load_file

    sd = load_file(path)
    with torch.no_grad():
        for key, value in sd.items():
            name = key.removeprefix("diffusion_model.")
            if name.endswith(".lora_down.weight"):
                module = model.get_submodule(name[: -len(".lora_down.weight")])
                up = sd[key.replace(".lora_down.", ".lora_up.")].float()
                alpha = sd.get(key.replace(".lora_down.weight", ".alpha"))
                scale = weight * (float(alpha) / value.shape[0] if alpha is not None else 1.0)
                dev = module.weight.device
                module.weight += (scale * up.to(dev) @ value.float().to(dev)).to(module.weight.dtype)
            elif name.endswith(".diff_b"):
                module = model.get_submodule(name[: -len(".diff_b")])
                module.bias += (weight * value.float().to(module.bias.device)).to(module.bias.dtype)
            elif name.endswith(".diff"):
                module = model.get_submodule(name[: -len(".diff")])
                module.weight += (weight * value.float().to(module.weight.device)).to(module.weight.dtype)


def load_pipeline():
    from diffusers import FlowMatchEulerDiscreteScheduler
    from videox_fun.models import AutoencoderKLWan3_8, AutoTokenizer, Wan2_2Transformer3DModel, WanT5EncoderModel
    from videox_fun.pipeline import Wan2_2FunControlPipeline
    from videox_fun.utils import filter_kwargs

    class GpuPipeline(Wan2_2FunControlPipeline):
        # T5 stays on the CPU (the fixed prompt is encoded once below), which would otherwise make diffusers pick it.
        @property
        def _execution_device(self):
            return torch.device("cuda")

        def encode_prompt(self, *args, **kwargs):
            if getattr(self, "cached_prompt_embeds", None) is None:
                return super().encode_prompt(*args, **kwargs)
            return self.cached_prompt_embeds

        def decode_video(self, latents, stop=None):
            """The first `stop` uint8 frames (stop, H, W, 3) of `latents`, see fun5b.vae_decode.decode_frames.
            The VAE decode is the GPU memory peak of a chunk: 8.2GB beyond the weights (whatever the length), of which
            ~1.6GB are cuDNN workspaces. Short of memory, cuDNN does not fail but falls back to slower convolution
            plans, and PyTorch keeps them for the rest of the process: the old decode (10.4GB) next to the DiT
            (~10.1GB free) took 39-41s instead of 31s, and its output was 1-2 levels off on ~1.7% of the pixels. So:
            the cached, unused blocks of the DiT's activations are released first, and if even then it does not
            fit (another GPU user such as MuseTalk), the DiT waits in host RAM (moving it out and back costs ~14s).
            Ask before decoding: an out-of-memory midway through a decode wasted 70-100s. The memory a decode needs
            is measured on each successful one."""
            torch.cuda.empty_cache()
            frames = latents.shape[2]
            need = self.decode_need.get(frames)
            if frames not in self.decode_offload and (need is None or _free_gpu() > need + 0.5 * 2**30):
                before = torch.cuda.memory_allocated()
                torch.cuda.reset_peak_memory_stats()
                try:
                    out = decode_frames(self.vae, latents, stop)
                    self.decode_need[frames] = torch.cuda.max_memory_allocated() - before
                    return out
                except torch.OutOfMemoryError:
                    self.decode_offload.add(frames)
                    print(f"VAE decode of {frames} latent frames out of memory with the DiT on the GPU: from now "
                          "on with the DiT in host RAM", flush=True)
            self.transformer.to("cpu")
            torch.cuda.empty_cache()
            try:
                return decode_frames(self.vae, latents, stop)
            finally:
                self.transformer.to("cuda")

    # VideoX-Fun reads the .pth checkpoints (T5 11GB, VAE 2.8GB) fully into RAM; memory-map them instead.
    torch_load = torch.load
    torch.load = lambda *args, **kwargs: torch_load(*args, **{"mmap": True, **kwargs})
    try:
        return _load_pipeline(GpuPipeline, AutoencoderKLWan3_8, AutoTokenizer, Wan2_2Transformer3DModel,
                              WanT5EncoderModel, FlowMatchEulerDiscreteScheduler, filter_kwargs)
    finally:
        torch.load = torch_load


