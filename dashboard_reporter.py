"""Push this node's status to the fleet dashboard — see doc_api/API_INTEGRATION.md
for the full API this implements (5 push endpoints, auth header, recommended cadence).

Config lives in .env (DASHBOARD_URL, INGEST_TOKEN, NODE_NAME), read via the same
resolve_env_path() mechanism as google_drive_upload.py — .env survives app
reinstalls at ~/.config/byscom-render/.env. Disabled (every push is a no-op)
whenever DASHBOARD_URL or INGEST_TOKEN is unset: right now it only points at a
throwaway test dashboard, and the real URL/token will be swapped in later purely
via .env, no code change needed.

The token — NOT a node_id in the URL — is what identifies this node to the
dashboard (1 token per node, generated by the dashboard's "Node keys" UI or its
create_node script; there is no shared secret / no unauthenticated mode). None of
the 5 endpoints take a node_id path segment; `NODE_NAME` below is purely a
display label the dashboard shows next to the node, unrelated to its identity.

Every push function catches its own errors and logs instead of raising — a
dashboard restart/timeout must never take down queue_worker.py's render loop
(same principle as google_drive_upload's per-job try/except in queue_worker).
"""
import os
import shutil
import socket
import subprocess
import time
from datetime import datetime
from pathlib import Path

import requests
from dotenv import load_dotenv

import database as db
import tts_db
from env_path import resolve_env_path

ROOT = Path(__file__).parent
ENV_PATH = resolve_env_path(ROOT / ".env")
_ENV_MTIME = 0.0

JOB_STATUSES = ("queued", "rendering", "done", "failed")
TTS_STATUSES = ("pending", "submitting", "retry_wait", "done", "failed_retryable", "failed_permanent")


def _reload_env_if_changed():
    """Re-read .env when it changes on disk, same reasoning as google_drive_upload's
    version: DASHBOARD_URL/INGEST_TOKEN saved later through a settings UI must reach
    this long-running process without a full worker restart."""
    global _ENV_MTIME
    try:
        mtime = ENV_PATH.stat().st_mtime
    except OSError:
        return
    if mtime != _ENV_MTIME:
        load_dotenv(ENV_PATH, override=True)
        _ENV_MTIME = mtime


def _env(name, default=""):
    _reload_env_if_changed()
    return os.environ.get(name, default).strip()


def dashboard_enabled():
    # No unauthenticated mode in this API: a request with no/wrong token 401s
    # outright, so without a token there's nothing a push could accomplish.
    return bool(_env("DASHBOARD_URL")) and bool(_env("INGEST_TOKEN"))


def _node_name():
    """Display label only (dashboard shows it next to the node) — the token is
    what actually identifies the node, so this has zero effect on routing/identity."""
    return _env("NODE_NAME") or socket.gethostname()


def _post(path, payload):
    url = _env("DASHBOARD_URL").rstrip("/") + path
    headers = {"Content-Type": "application/json", "X-Ingest-Token": _env("INGEST_TOKEN")}
    r = requests.post(url, headers=headers, json=payload, timeout=10)
    r.raise_for_status()


# ---------------------------------------------------------------- settings (UI)

def _update_env_file(updates):
    """Ghi/đè KEY=VALUE vào .env, giữ nguyên mọi dòng khác — cùng cách làm với
    google_drive_upload._update_env_file. chmod 600 vì INGEST_TOKEN là bí mật."""
    lines = ENV_PATH.read_text().splitlines() if ENV_PATH.exists() else []
    seen = set()
    for i, line in enumerate(lines):
        if "=" not in line or line.lstrip().startswith("#"):
            continue
        key = line.split("=", 1)[0].strip()
        if key in updates:
            lines[i] = f"{key}={updates[key]}"
            seen.add(key)
    missing = [k for k in updates if k not in seen]
    if missing:
        if lines and lines[-1].strip():
            lines.append("")
        lines.extend(f"{k}={updates[k]}" for k in missing)
    ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
    ENV_PATH.write_text("\n".join(lines) + "\n")
    os.chmod(ENV_PATH, 0o600)
    for k, v in updates.items():
        os.environ[k] = v
    global _ENV_MTIME
    _ENV_MTIME = ENV_PATH.stat().st_mtime  # we just wrote it ourselves — don't reload right back


def save_settings(dashboard_url, ingest_token, node_name):
    """Same trust model as tts_config.save_config(): the UI round-trips the current
    secret back in the form, so an intentionally-cleared field really means 'remove
    it' — no separate 'leave unchanged' sentinel."""
    _update_env_file({
        "DASHBOARD_URL": (dashboard_url or "").strip(),
        "INGEST_TOKEN": (ingest_token or "").strip(),
        "NODE_NAME": (node_name or "").strip(),
    })


def status():
    return {
        "configured": dashboard_enabled(),
        "dashboard_url": _env("DASHBOARD_URL") or None,
        "ingest_token": _env("INGEST_TOKEN") or None,
        "node_name": _env("NODE_NAME") or None,
    }


def test_push():
    """Push one real node snapshot right now and let errors propagate — unlike
    push_node_snapshot() (used by the background loop, which must never raise), this is
    for the Save button: the UI needs to know immediately if the URL/token don't
    actually work, not just that they were written to .env."""
    if not dashboard_enabled():
        raise RuntimeError("Chưa điền đủ Dashboard URL + Ingest Token.")
    _post("/api/ingest/node", _build_node_payload())


# ---------------------------------------------------------------- node resources

def _gpu_snapshot():
    try:
        out = subprocess.run(
            ["nvidia-smi",
             "--query-gpu=index,name,utilization.gpu,memory.used,memory.total,temperature.gpu",
             "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=15,
        )
        if out.returncode != 0:
            return []
        gpus = []
        for line in out.stdout.strip().splitlines():
            parts = [p.strip() for p in line.split(",")]
            if len(parts) != 6:
                continue
            idx, name, util, mem_used, mem_total, temp = parts
            gpus.append({
                "index": int(idx), "name": name, "util_percent": int(float(util)),
                "mem_used_mb": int(float(mem_used)), "mem_total_mb": int(float(mem_total)),
                "temp_c": int(float(temp)),
            })
        return gpus
    except Exception:
        return []


def _dir_size_bytes(path):
    """Real content size of `path`, not shutil.disk_usage()'s whole-partition figure —
    renders/avatar_cache/uploads all live on the same disk, so disk_usage() alone would
    report the same used/total for all three instead of each folder's own footprint."""
    total = 0
    try:
        for entry in Path(path).rglob("*"):
            try:
                if entry.is_file():
                    total += entry.stat().st_size
            except OSError:
                continue
    except OSError:
        pass
    return total


def _disk_usage(path):
    try:
        partition_total, _used, _free = shutil.disk_usage(path)
    except OSError:
        return None
    return {"used_gb": round(_dir_size_bytes(path) / 1e9, 1), "total_gb": round(partition_total / 1e9, 1)}


def _disk_usage_combined(paths):
    """Sum of several directories reported as one dashboard 'avatar_cache' bucket —
    the real avatar-cache footprint spans LatentSync's own precompute cache
    (ROOT/avatar_cache) plus MuseTalk's video-render and realtime caches
    (engines/MuseTalk/results/v15/avatars_video|avatars_realtime), which live
    apart on disk but are all "avatar cache" from a monitoring standpoint."""
    existing = [Path(p) for p in paths if Path(p).is_dir()]
    if not existing:
        return None
    try:
        partition_total, _used, _free = shutil.disk_usage(existing[0])
    except OSError:
        return None
    used = sum(_dir_size_bytes(p) for p in existing)
    return {"used_gb": round(used / 1e9, 1), "total_gb": round(partition_total / 1e9, 1)}


_DISKS_CACHE = {"at": 0.0, "value": None}
_DISKS_CACHE_SECONDS = 60  # rglob over renders/avatar_cache/uploads is real disk I/O —
                           # too slow to redo on push_node_snapshot's 10s cadence


def _disks_snapshot():
    now = time.time()
    if _DISKS_CACHE["value"] is None or now - _DISKS_CACHE["at"] >= _DISKS_CACHE_SECONDS:
        _DISKS_CACHE["value"] = {
            "renders": _disk_usage(db.RENDERS_DIR),
            "avatar_cache": _disk_usage_combined([
                ROOT / "avatar_cache",
                ROOT / "engines" / "MuseTalk" / "results" / "v15" / "avatars_video",
                ROOT / "engines" / "MuseTalk" / "results" / "v15" / "avatars_realtime",
            ]),
            "uploads": _disk_usage(ROOT / "uploads"),
        }
        _DISKS_CACHE["at"] = now
    return _DISKS_CACHE["value"]


def _last_backup_at():
    backups = sorted((ROOT / "backups").glob("jobs_*.db"))
    if not backups:
        return None
    try:
        ts = backups[-1].stem.split("_", 1)[1]  # "20260821_120000"
        return datetime.strptime(ts, "%Y%m%d_%H%M%S").strftime("%Y-%m-%d %H:%M")
    except Exception:
        return None


def _current_job_label():
    rendering = db.list_rendering_jobs()
    if not rendering:
        return None
    return ", ".join(f"#{j['id']} {j['name']}" for j in rendering)


def _build_node_payload():
    try:
        import psutil
        cpu_percent = psutil.cpu_percent(interval=0.5)
        mem = psutil.virtual_memory()
        ram_used_gb, ram_total_gb = round(mem.used / 1e9, 1), round(mem.total / 1e9, 1)
    except Exception:
        cpu_percent, ram_used_gb, ram_total_gb = 0, 0, 0
    gpus = _gpu_snapshot()
    return {
        "name": _node_name(),
        "gpu_tag": gpus[0]["name"] if gpus else "",  # non-nullable string on the dashboard's schema
        "cpu_percent": cpu_percent,
        "load_avg": list(os.getloadavg()),
        "ram_used_gb": ram_used_gb,
        "ram_total_gb": ram_total_gb,
        "disks": _disks_snapshot(),
        "gpus": gpus,
        "current_job": _current_job_label(),
        "last_backup_at": _last_backup_at(),
    }


def push_node_snapshot():
    if not dashboard_enabled():
        return
    try:
        _post("/api/ingest/node", _build_node_payload())
    except Exception as e:
        print(f"[dashboard] push node snapshot failed: {e}", flush=True)


# ---------------------------------------------------------------- jobs / tts

def push_jobs():
    if not dashboard_enabled():
        return
    jobs = db.list_jobs(limit=200)
    counts = {status: 0 for status in JOB_STATUSES}
    for j in jobs:
        if j["status"] in counts:
            counts[j["status"]] += 1
    recent = []
    for j in sorted(jobs, key=lambda j: j["id"], reverse=True):
        if j["status"] not in JOB_STATUSES:  # dashboard schema has no 'cancelled'
            continue
        entry = {
            "id": j["id"], "name": j["name"], "status": j["status"],
            "model": f"{j['engine']} / {j['model_res']}", "priority": j["priority"],
            "retries": j["retries"], "error": j["error"],
            "started_at": j["started_at"], "finished_at": j["finished_at"],
        }
        if j.get("drive_link"):
            entry["drive_link"] = j["drive_link"]
        if j.get("drive_error"):
            entry["drive_error"] = j["drive_error"]
        recent.append(entry)
        if len(recent) >= 20:
            break
    try:
        _post("/api/ingest/node/jobs", {"counts": counts, "recent": recent})
    except Exception as e:
        print(f"[dashboard] push jobs failed: {e}", flush=True)


def push_tts():
    if not dashboard_enabled():
        return
    counts = tts_db.status_counts()
    recent = [
        {
            "id": j["id"], "text": j["text"], "provider": j["provider"], "voice_id": j["voice_id"],
            "status": j["status"], "attempt_count": j["attempt_count"], "last_error": j["last_error"],
            "created_at": j["created_at"], "render_job_id": j["render_job_id"],
        }
        for j in tts_db.list_jobs(limit=200)
    ]
    payload = {
        "counts": {status: counts.get(status, 0) for status in TTS_STATUSES},
        "recent": recent,
        "rate_limits": tts_db.list_rate_limits(),
    }
    try:
        _post("/api/ingest/node/tts", payload)
    except Exception as e:
        print(f"[dashboard] push tts failed: {e}", flush=True)


# ---------------------------------------------------------------- stats / batches

def push_stats():
    if not dashboard_enabled():
        return
    try:
        _post("/api/ingest/node/stats", db.stats_summary())
    except Exception as e:
        print(f"[dashboard] push stats failed: {e}", flush=True)


_BATCH_PUSH_CACHE = {}  # batch_id -> last (total, done, failed, pending) actually posted


def push_batches():
    """list_batch_ids() returns EVERY batch ever recorded, with no cutoff — without
    the cache below, a batch finished months ago gets its unchanged progress
    re-queried and re-posted every cycle forever, growing the cost of this call
    (DB query + HTTP round-trip per batch) without bound as history accumulates."""
    if not dashboard_enabled():
        return
    for batch_id in tts_db.list_batch_ids():
        progress = tts_db.batch_progress(batch_id)
        if progress["total"] == 0:
            continue
        key = (progress["total"], progress["done"], progress["failed"], progress["pending"])
        if _BATCH_PUSH_CACHE.get(batch_id) == key:
            continue
        excel_path = tts_db.get_batch_excel(batch_id)
        batch_name = Path(excel_path).name if excel_path else batch_id
        try:
            _post("/api/ingest/node/batches", {"batch_name": batch_name, **progress})
            _BATCH_PUSH_CACHE[batch_id] = key
        except Exception as e:
            print(f"[dashboard] push batch {batch_id} failed: {e}", flush=True)


# ---------------------------------------------------------------- background loop

def run_forever(is_running):
    """Dedicated thread, NOT the main render-claim loop: that loop blocks for the
    whole duration of a render (can be 1h+), which would starve these pushes right
    when the dashboard most wants live GPU/job status. is_running: callable polled
    each cycle so the thread exits promptly on worker shutdown."""
    last_slow = 0.0
    while is_running():
        try:
            push_node_snapshot()
            push_jobs()
            push_tts()
            if time.time() - last_slow >= 60:
                push_stats()
                push_batches()
                last_slow = time.time()
        except Exception as e:
            print(f"[dashboard] push cycle error (continuing): {e}", flush=True)
        time.sleep(10)
